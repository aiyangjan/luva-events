export function translate(locale: Locale, key: string, vars?: Record<string, string | number>) {
  const table = dictionaries[locale] || en;
  let text = table[key] || en[key] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

export function translateError(locale: Locale, message: string | null | undefined, fallbackKey = "err.failed") {
  if (!message) return translate(locale, fallbackKey);
  const key = ERROR_MESSAGE_KEYS[message];
  if (key) return translate(locale, key);
  // Already Chinese or unknown — show as-is
  return message;
}
